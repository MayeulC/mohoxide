//! `--dump-api <DIR>`: builds both VMs' engine API (no game files needed) and
//! writes, per VM, the Luau definitions and EmmyLua annotations, the list of
//! undocumented functions (`undocumented.md`), plus the
//! comparison with FAF's annotations with `--faf-compare`.
//! The output isn't checked in: `cargo run -- --dump-api docs/api`
//! (`docs/api/` is ignored by git).

use std::path::Path;
use std::sync::{Arc, RwLock};

use mlua::prelude::*;

use super::registry::ApiRegistry;
use super::{compare, emit};
use crate::engine::lua::script_cache::ScriptCache;
use crate::engine::vfs::Vfs;

fn empty_vfs() -> Arc<RwLock<Vfs>> {
    Arc::new(RwLock::new(Vfs::new(Vec::new(), Vec::new()).expect("empty vfs")))
}

/// The sim VM with its engine API registered, as `Engine::new` builds it,
/// without the game's files.
pub fn sim_vm() -> LuaResult<Lua> {
    let vfs = empty_vfs();
    let lua = Lua::new();
    lua.set_app_data(vfs.clone());
    lua.set_app_data(Arc::new(ScriptCache::new(vfs)));
    crate::engine::api::register_safe(&lua)?;
    Ok(lua)
}

/// The user VM with its engine API registered, without the game's files.
pub fn user_vm() -> LuaResult<crate::ui::UserVm> {
    crate::ui::UserVm::new(empty_vfs())
}

/// The generated files: (file name, contents). The FAF comparison is
/// included when `faf` (the FAF checkout) is given.
pub fn generate(faf: Option<&Path>) -> LuaResult<Vec<(String, String)>> {
    let sim = sim_vm()?;
    let user = user_vm()?;
    let mut files = Vec::new();
    let mut compare_md = String::from(
        "# Engine API vs FAF's annotations\n\nGenerated by `cargo run -- --dump-api docs/api --faf-compare`. FAF's `/engine` annotations are\n\
         community documentation, not ground truth: read this as a list of things to look at.\n\n",
    );
    {
        let sim_reg = sim.app_data_ref::<ApiRegistry>().ok_or_else(|| LuaError::runtime("no ApiRegistry"))?;
        let user_reg = user.lua().app_data_ref::<ApiRegistry>().ok_or_else(|| LuaError::runtime("no ApiRegistry"))?;
        files.push(("undocumented.md".into(), emit::undocumented(&[("sim", &sim_reg), ("user", &user_reg)])));
    }
    for (vm, lua, faf_dir) in [("sim", &sim, "Sim"), ("user", user.lua(), "User")] {
        let reg = lua.app_data_ref::<ApiRegistry>().ok_or_else(|| LuaError::runtime("no ApiRegistry"))?;
        files.push((format!("{vm}.d.luau"), emit::luau(&reg, vm)));
        files.push((format!("{vm}.lua"), emit::emmy(&reg, vm)));
        if let Some(faf) = faf {
            let api = compare::read_faf(faf, faf_dir).map_err(LuaError::external)?;
            compare_md.push_str(&compare::report(&reg, &api, vm).0);
        }
    }
    if faf.is_some() {
        files.push(("faf-compare.md".into(), compare_md));
    }
    Ok(files)
}

/// Writes [`generate`]'s files into `dir`.
pub fn write(dir: &Path, faf: Option<&Path>) -> LuaResult<Vec<String>> {
    std::fs::create_dir_all(dir).map_err(LuaError::external)?;
    let mut names = Vec::new();
    for (name, text) in generate(faf)? {
        std::fs::write(dir.join(&name), text).map_err(LuaError::external)?;
        names.push(name);
    }
    Ok(names)
}
