/// Translates SupCom Lua source to valid Luau before execution.
///
/// SupCom runs a custom Lua 5.0 interpreter with extensions beyond standard Lua.
/// Scan of the FA/FAF codebase (30k+ files) found these syntax extensions:
///
/// | Extension          | SupCom | Standard Lua 5.4 | Luau |
/// |--------------------|--------|------------------|------|
/// | `!=`               | ✓      | `~=` only        | ✗ (rewritten to `~=`)         |
/// | `# comment`        | ✓      | shebang line 1   | ✗ (rewritten to `--`)         |
/// | `continue`         | ✓      | ✗                | ✓ (native)                    |
/// | `{&N &M}`          | ✓      | ✗                | ✗ (stripped to `{}`)          |
/// | `&` `\|` `<<` `>>` | ✓      | ✓ (5.3+)         | ✗ (rewritten to `bit32.*`)    |
/// | `for k,v in t` (table) | ✓ (5.0)| ✗           | ✗ (`__forin(t)` → `next, t`) |
/// | implicit `arg`     | ✓ (5.0)| ✗                | ✗ (`local arg = table.pack(...)`) |
///
/// The bitwise pass parses with `full_moon` configured for Lua 5.3 **and** Luau
/// at once, so `continue` and bitwise operators coexist without any masking.
/// A leading UTF-8 BOM (rejected by `full_moon` and the Luau loader) is stripped
/// first; line-leading `#` comments are converted to `--` by [`hash_comment`].
///
/// Add a new submodule here if additional SupCom quirks surface.
pub fn translate(source: &str) -> String {
    let s = strip_bom(source);
    let s = hash_comment::rewrite(s);
    let s = neq::rewrite(&s);
    let s = prealloc::strip(&s);
    let s = bitwise::rewrite(&s);
    let s = vararg::rewrite(&s);
    forin::rewrite(&s)
}

/// Strips a leading UTF-8 BOM, which `full_moon` and the Luau loader both reject.
fn strip_bom(source: &str) -> &str {
    source.strip_prefix('\u{feff}').unwrap_or(source)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strip_bom_removes_leading_bom_only() {
        assert_eq!(strip_bom("\u{feff}local x = 1"), "local x = 1");
        assert_eq!(strip_bom("local x = 1"), "local x = 1");
        // A `#` line is NOT dropped here — hash_comment converts it to `--`.
        assert_eq!(strip_bom("# header\nx = 1"), "# header\nx = 1");
    }

    /// A BOM-prefixed `#` header still becomes a comment: BOM is stripped, then
    /// hash_comment converts the now-line-leading `#`.
    #[test]
    fn bom_then_hash_header_translates() {
        assert_eq!(
            translate("\u{feff}# autogenerated\nlocal x = 1"),
            "-- autogenerated\nlocal x = 1"
        );
    }

    /// End-to-end: a translated bitwise expression must actually run under the
    /// Luau VM (i.e. `bit32.*` exists and the rewrite is semantically correct).
    #[test]
    fn translated_bitwise_executes_under_luau() {
        let src = translate("function f(op, b) return (op & 0x1f) | (b << 5) end");
        let lua = mlua::Lua::new();
        lua.load(&src).exec().expect("translated chunk should load and run");
        let f: mlua::Function = lua.globals().get("f").unwrap();
        let result: i64 = f.call((5i64, 2i64)).unwrap();
        assert_eq!(result, (5 & 0x1f) | (2 << 5)); // 5 | 64 = 69
    }

    /// `continue` must survive translation and execute natively in Luau.
    #[test]
    fn translated_continue_executes_under_luau() {
        let src = translate(
            "function sum_odd(n)\n\
             \tlocal s = 0\n\
             \tfor i = 1, n do\n\
             \t\tif i & 1 == 0 then continue end\n\
             \t\ts = s + i\n\
             \tend\n\
             \treturn s\n\
             end",
        );
        let lua = mlua::Lua::new();
        lua.load(&src).exec().expect("translated chunk should load and run");
        let f: mlua::Function = lua.globals().get("sum_odd").unwrap();
        let result: i64 = f.call(6i64).unwrap();
        assert_eq!(result, 1 + 3 + 5);
    }
}
