#!/usr/bin/env python3
"""Generates a stress-test scenario with N army slots on a stock 81 km map.

The scenario reuses the stock map's .scmap by VFS path (nothing is copied);
only the scenario, save (start markers) and script files are written, to
dev/vault/maps/stress_<n>/. Start spots are spread over flat land: candidate
points on a grid that are above water with flat surroundings, then
farthest-point sampling picks N of them.

Usage: python3 dev/scenes/stress/gen_stress_map.py 16
       cargo run --release -- --vault dev/vault --map /maps/stress_16/stress_16_scenario.lua --no-ai --script dev/scenes/stress/stress.lua
"""
import os
import struct
import sys

FA = "../original supreme commander unpacked/maps"
MAP = "SCMP_030"  # 4096 x 4096, the stock map with the most flat land (150 start spots)
WATER = 17.5


def heights(path):
    b = open(path, "rb").read()
    o = 30
    preview, = struct.unpack("<i", b[o:o + 4])
    o += 4 + preview
    _version, w, h = struct.unpack("<iii", b[o:o + 12])
    scale, = struct.unpack("<f", b[o + 12:o + 16])
    o += 16
    raw = struct.unpack("<%dH" % ((w + 1) * (h + 1)), b[o:o + (w + 1) * (h + 1) * 2])
    return w, h, lambda x, z: raw[int(z) * (w + 1) + int(x)] * scale


def starts(n, w, h, at):
    step, reach = 48, 40
    candidates = []
    for z in range(reach, h - reach, step):
        for x in range(reach, w - reach, step):
            ring = [at(x + dx, z + dz) for dx in (-reach, 0, reach) for dz in (-reach, 0, reach)]
            if min(ring) > WATER + 1.5 and max(ring) - min(ring) < 6:
                candidates.append((x, z))
    if len(candidates) < n:
        sys.exit(f"only {len(candidates)} flat land spots for {n} armies")
    cx, cz = w / 2, h / 2
    chosen = [min(candidates, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cz) ** 2)]
    dist = [((p[0] - chosen[0][0]) ** 2 + (p[1] - chosen[0][1]) ** 2) for p in candidates]
    while len(chosen) < n:
        i = max(range(len(candidates)), key=lambda k: dist[k])
        chosen.append(candidates[i])
        px, pz = candidates[i]
        dist = [min(d, (p[0] - px) ** 2 + (p[1] - pz) ** 2) for d, p in zip(dist, candidates)]
    return chosen


def main():
    n = int(sys.argv[1])
    name = f"stress_{n}"
    out = os.path.join("dev", "vault", "maps", name)
    os.makedirs(out, exist_ok=True)
    w, h, at = heights(os.path.join(FA, MAP, f"{MAP}.scmap"))
    spots = starts(n, w, h, at)
    armies = [f"ARMY_{i + 1}" for i in range(n)]
    with open(os.path.join(out, f"{name}_scenario.lua"), "w") as f:
        f.write(f"""version = 3
ScenarioInfo = {{
    name = "Stress {n}",
    description = "Generated by dev/scenes/stress/gen_stress_map.py: {n} army slots on {MAP}.",
    type = 'skirmish',
    starts = true,
    preview = '',
    size = {{{w}, {h}}},
    map = '/maps/{MAP}/{MAP}.scmap',
    save = '/maps/{name}/{name}_save.lua',
    script = '/maps/{name}/{name}_script.lua',
    norushradius = 0,
    Configurations = {{
        ['standard'] = {{
            teams = {{
                {{ name = 'FFA', armies = {{{','.join(repr(a) for a in armies)},}} }},
            }},
            customprops = {{
            }},
        }},
    }}}}
""")
    with open(os.path.join(out, f"{name}_script.lua"), "w") as f:
        f.write("""local ScenarioUtils = import('/lua/sim/ScenarioUtilities.lua')

function OnPopulate()
    ScenarioUtils.InitializeArmies()
end

function OnStart(self)
end
""")
    markers = "".join(
        f"""                ['{a}'] = {{
                    ['color'] = STRING( 'ff800080' ),
                    ['type'] = STRING( 'Blank Marker' ),
                    ['prop'] = STRING( '/env/common/props/markers/M_Blank_prop.bp' ),
                    ['orientation'] = VECTOR3( 0, 0, 0 ),
                    ['position'] = VECTOR3( {x + 0.5}, {at(x, z):.4f}, {z + 0.5} ),
                }},
"""
        for a, (x, z) in zip(armies, spots)
    )
    army_blocks = "".join(
        f"""        ['{a}'] =
        {{
            personality = '',
            plans = '',
            color = 0,
            faction = 0,
            Economy = {{ mass = 0, energy = 0, }},
            Alliances = {{ }},
            ['Units'] = GROUP {{
                orders = '',
                platoon = '',
                Units = {{
                    ['INITIAL'] = GROUP {{ orders = '', platoon = '', Units = {{ }}, }},
                }},
            }},
            PlatoonBuilders = {{ next_platoon_builder_id = '0', Builders = {{ }}, }},
        }},
"""
        for a in armies
    )
    with open(os.path.join(out, f"{name}_save.lua"), "w") as f:
        f.write(f"""Scenario = {{
    next_area_id = '1',
    Props = {{ }},
    Areas = {{ }},
    MasterChain = {{
        ['_MASTERCHAIN_'] = {{
            Markers = {{
{markers}            }},
        }},
    }},
    Chains = {{ }},
    next_queue_id = '1',
    Orders = {{ }},
    next_platoon_id = '1',
    Platoons = {{ }},
    next_army_id = '{n + 1}',
    next_group_id = '{n + 1}',
    next_unit_id = '1',
    Armies =
    {{
{army_blocks}    }},
}}
""")
    print(f"wrote {out}: {n} armies on {MAP}")


if __name__ == "__main__":
    main()
