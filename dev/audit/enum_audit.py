#!/usr/bin/env python3
"""Enum audit: moho's enums (from the binaries) vs FAF's `engine/Enums.lua`
vs the names our source uses.

Moho registers each enum member as `push value; push "name"` before a call,
so the members and their values can be read from the code of MohoEngine.dll
and FA's exe. For every FAF enum alias this prints the members moho has
(with values), which FAF lists, and which our Rust / Lua names as a string
literal: a member moho has that we never name, or one of ours moho doesn't
have, is worth a look. Where our source keeps an ordered list (`COMMAND_CAPS`,
`TOGGLE_CAPS`), its order is checked against moho's values.

    python3 dev/audit/enum_audit.py > docs/api/enums.md

Options: --game DIR (default ../Supreme Commander Forged Alliance),
--fa DIR (default ../fa).
"""
import argparse
import glob
import os
import re
import struct
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))


class Pe:
    def __init__(self, path):
        self.d = open(path, 'rb').read()
        pe = struct.unpack_from('<I', self.d, 0x3c)[0]
        n = struct.unpack_from('<H', self.d, pe + 6)[0]
        opt = struct.unpack_from('<H', self.d, pe + 20)[0]
        self.base = struct.unpack_from('<I', self.d, pe + 24 + 28)[0]
        self.sections = [struct.unpack_from('<IIII', self.d, pe + 24 + opt + 40 * i + 8) for i in range(n)]

    def off(self, va):
        for vs, va0, rs, ra in self.sections:
            if self.base + va0 <= va < self.base + va0 + rs:
                return va - self.base - va0 + ra
        return None

    def cstr(self, va):
        o = self.off(va)
        if o is None:
            return None
        e = self.d.find(b'\0', o)
        s = self.d[o:e]
        return s.decode() if 0 < len(s) < 64 and re.fullmatch(rb'[A-Za-z_][A-Za-z0-9_]*', s) else None


def moho_enums(paths):
    """{name: value} for every `push imm; push "Name"` pair in the code."""
    out = {}
    for p in paths:
        pe = Pe(p)
        d = pe.d
        for m in re.finditer(rb'(?:\x6a(.)|\x68(.{4}))\x68(.{4})', d, re.S):
            name = pe.cstr(struct.unpack('<I', m.group(3))[0])
            if not name:
                continue
            value = m.group(1)[0] if m.group(1) is not None else struct.unpack('<i', m.group(2))[0]
            out.setdefault(name, value)
    return out


def faf_enums(fa):
    """{alias: [member]} from FAF's `engine/Enums.lua` (string members)."""
    out, alias = {}, None
    for line in open(os.path.join(fa, 'engine', 'Enums.lua'), encoding='utf-8', errors='replace'):
        m = re.match(r'---@alias\s+(\w+)', line)
        if m:
            alias = m.group(1)
            out[alias] = []
            continue
        m = re.match(r'---\|\s*"([^"]+)"', line) or re.match(r"---\|\s*'([^']+)'", line)
        if m and alias:
            out[alias].append(m.group(1))
        elif not line.startswith('---'):
            alias = None
    return {k: v for k, v in out.items() if v}


def our_literals():
    out = set()
    for f in glob.glob(os.path.join(REPO, 'src', '**', '*.rs'), recursive=True) + glob.glob(os.path.join(REPO, 'src', '**', '*.lua'), recursive=True):
        text = open(f, encoding='utf-8', errors='replace').read()
        out.update(re.findall(r'"([A-Za-z_][A-Za-z0-9_ ]*)"', text))
        if f.endswith('.lua'):
            out.update(re.findall(r"'([A-Za-z_][A-Za-z0-9_ ]*)'", text))
    return out


def our_ordered(name):
    """The members of our `const NAME: [&str; N]` list, in order."""
    for f in glob.glob(os.path.join(REPO, 'src', '**', '*.rs'), recursive=True):
        text = open(f, encoding='utf-8', errors='replace').read()
        m = re.search(r'const\s+' + name + r'\s*:\s*\[&str;\s*\d+\]\s*=\s*\[(.*?)\];', text, re.S)
        if m:
            return os.path.relpath(f, REPO), re.findall(r'"([^"]+)"', m.group(1))
    return None, []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--game', default=os.path.join(REPO, '..', 'Supreme Commander Forged Alliance'))
    ap.add_argument('--fa', default=os.path.join(REPO, '..', 'fa'))
    args = ap.parse_args()
    bins = [p for p in (os.path.join(args.game, 'bin', n) for n in ('MohoEngine.dll', 'SupremeCommander.exe')) if os.path.exists(p)]
    moho = moho_enums(bins)
    faf = faf_enums(args.fa)
    ours = our_literals()

    print('# Enums: moho vs FAF vs ours\n')
    print('Generated by `python3 dev/audit/enum_audit.py`. "moho" = registered as `push value; push "name"` in')
    print(f'{", ".join(os.path.basename(b) for b in bins)} (value shown); "FAF" = `engine/Enums.lua`; "ours" = a string')
    print('literal in `src/`. Look at rows where the columns disagree.\n')
    for alias, members in faf.items():
        prefix = os.path.commonprefix(members) if len(members) > 1 else ''
        prefix = prefix[:prefix.rfind('_') + 1] if '_' in prefix else ''
        names = list(members)
        if prefix:
            names += sorted(n for n in moho if n.startswith(prefix) and n not in members)
            # (A bare prefix is code stripping it, `strip_prefix("UWRC_")`:
            # such members show as not ours though the code handles them.)
            names += sorted(n for n in ours if n.startswith(prefix) and n != prefix and n not in names)
        rows = [(n, moho.get(n), n in members, n in ours) for n in names]
        print(f'## {alias} ({len(members)} in FAF)\n')
        print('| member | moho value | FAF | ours |')
        print('|---|---|---|---|')
        for n, v, f, o in rows:
            print(f'| `{n}` | {"" if v is None else v} | {"yes" if f else "**no**"} | {"yes" if o else "**no**"} |')
        print()
    for const, prefix in (('COMMAND_CAPS', 'RULEUCC_'), ('TOGGLE_CAPS', 'RULEUTC_')):
        print(f'## Order of our `{const}` (bit n = n-th name) vs moho\'s values\n')
        files = set()
        for f in glob.glob(os.path.join(REPO, 'src', '**', '*.rs'), recursive=True):
            if re.search(r'const\s+' + const + r'\s*:', open(f, encoding='utf-8', errors='replace').read()):
                files.add(os.path.relpath(f, REPO))
        for f in sorted(files):
            text = open(os.path.join(REPO, f), encoding='utf-8', errors='replace').read()
            m = re.search(r'const\s+' + const + r'\s*:\s*\[&str;\s*\d+\]\s*=\s*\[(.*?)\];', text, re.S)
            names = re.findall(r'"([^"]+)"', m.group(1)) if m else []
            bad = [(i, n, moho.get(n)) for i, n in enumerate(names) if moho.get(n) != 1 << i]
            print(f'- `{f}`: {len(names)} names; ' + ('all match moho (bit n = value 1<<n)' if not bad else 'differ: ' + ', '.join(f'`{n}` at bit {i}, moho {v}' for i, n, v in bad)))
        print()


if __name__ == '__main__':
    main()
